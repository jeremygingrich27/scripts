#!/usr/bin/env python3
"""Inequivalent displacement directions inside the unstable multiplet.

1. Magnetic symmetry of the cell from spglib (positions + MAGMOM).  Time reversal
   does not act on displacements, so primed operations act like ordinary ones.
2. Each operation g acts on the multiplet's eigenvector space as a d x d matrix
   D(g) = E^T G E.  (Checks the multiplet really is invariant.)
3. For every subgroup H (generated by up to 3 of the D(g)), the directions H
   leaves fixed are the null space of (D(h) - 1).  A 1-dim fixed space is an
   isotropy-subgroup direction, as ISOTROPY would list it.
4. Signed directions related by some D(g) are equivalent and are scanned once;
   so +u and -u become one scan when a symmetry maps one onto the other.

Writes PHONON_DIR/directions/<name>.npy (Cartesian pattern, N x 3, largest
single-atom displacement = 1 A) and directions.txt.  <name> =
<irrep>_<space group of the distorted cell, spinless, no '/'>, with a suffix if needed.

usage: find_directions.py PHONON_DIR IRREP_LABEL SYMPREC
"""
import itertools
import os
import sys
import numpy as np
import spglib
from dh_lib import read_poscar, symbols

d, irrep, symprec = sys.argv[1], sys.argv[2], float(sys.argv[3])
s = read_poscar(d + "/POSCAR")
mag = [float(x) for x in open(d + "/MAGMOM").read().split("=")[1].split()]
mult = np.load(d + "/multiplet.npz")
E, masses = mult["eigvecs"], mult["masses"]
L, frac = s["lattice"], s["frac"]
n, dim = len(frac), E.shape[1]
numbers = [s["species"].index(x) + 1 for x in symbols(s)]

# 1. magnetic symmetry operations
ops = spglib.get_magnetic_symmetry((L, frac, numbers, mag), symprec=symprec)


def atom_map(R, t):
    """perm[i] = index of the atom that atom i lands on under (R, t)."""
    new = frac @ R.T + t
    perm = []
    for p in new:
        diff = frac - p
        diff -= np.round(diff)
        perm.append(int(np.argmin(np.linalg.norm(diff @ L, axis=1))))
    return perm


# 2. representation matrices on the multiplet
reps = []
for R, t in zip(ops["rotations"], ops["translations"]):
    Rc = L.T @ R @ np.linalg.inv(L.T)          # Cartesian rotation
    G = np.zeros((3 * n, 3 * n))
    for i, j in enumerate(atom_map(R, t)):
        G[3 * j:3 * j + 3, 3 * i:3 * i + 3] = Rc
    D = E.T @ G @ E
    if np.linalg.norm(G @ E - E @ D) > 1e-3:
        sys.exit("multiplet is not invariant under the symmetry: check DEGEN_TOL / SYMPREC")
    if not any(np.allclose(D, X, atol=1e-6) for X in reps):
        reps.append(D)
print("%d magnetic operations, %d distinct on the %d-dim multiplet" % (len(ops["rotations"]), len(reps), dim))


def closure(gens):
    group = [np.eye(dim)]
    frontier = list(gens)
    while frontier:
        g = frontier.pop()
        if any(np.allclose(g, h, atol=1e-6) for h in group):
            continue
        group.append(g)
        frontier += [g @ h for h in group]
    return group


# 3. 1-dim fixed spaces of subgroups
candidates = []
for k in range(0, 4):
    for gens in itertools.combinations(reps, k):
        H = closure(gens)
        A = np.vstack([h - np.eye(dim) for h in H])
        _, sv, vt = np.linalg.svd(A)
        null = vt[np.concatenate([sv, np.zeros(dim - sv.size)]) < 1e-6]
        if len(null) == 1:
            candidates += [null[0], -null[0]]

# 4. merge signed directions related by symmetry
classes = []
for v in candidates:
    if not any(any(np.allclose(D @ c[0], v, atol=1e-5) for D in reps) for c in classes):
        classes.append([v])

os.makedirs(d + "/directions", exist_ok=True)
summary, used = [], set()
for v in classes:
    v = v[0]
    u = (E @ v / np.repeat(np.sqrt(masses), 3)).reshape(n, 3)
    u /= np.linalg.norm(u, axis=1).max()                # largest atom moves 1 A
    sign_equiv = any(np.allclose(D @ v, -v, atol=1e-5) for D in reps)
    test = frac + 0.05 * u @ np.linalg.inv(L)            # spinless group at 0.05 A
    sg = spglib.get_spacegroup((L, test, numbers), symprec=symprec).split()[0]
    name = "%s_%s" % (irrep, sg.replace("/", ""))
    k = 2
    while name in used:
        name = "%s_%s_%d" % (irrep, sg.replace("/", ""), k)
        k += 1
    used.add(name)
    np.save(d + "/directions/%s.npy" % name, u)
    summary.append("%-24s v=%s  +u~-u:%s  atoms moving:%d" % (
        name, np.round(v, 4), sign_equiv, int(np.sum(np.linalg.norm(u, axis=1) > 1e-3))))

open(d + "/directions.txt", "w").write("\n".join(summary) + "\n")
print("\n".join(summary))
